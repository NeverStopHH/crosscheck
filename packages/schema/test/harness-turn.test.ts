/**
 * The human text of a prompt turn (DESIGN.md §4): a harness delivers machine
 * text as user turns — Claude Code's background-task notifications, another
 * agent's or session's message, the IDE's file context, /loop ticks — and
 * their words (PR, CI, checks, pass, event) are nobody's task. Seen live on
 * 0.10.0: four consecutive pointers at unrelated trees, every one fired by
 * such a turn or by "mache weiter".
 *
 * EXACT, NOT AN HTML STRIPPER: a registry of named shapes, each with a
 * synthetic sample; any other angle-bracket text is the human's and stays.
 */
import { describe, expect, test } from "bun:test";

import {
  HARNESS_SCAN_MAX_CHARS,
  HARNESS_SHAPES,
  SYSTEM_NOTIFICATION_MARKER,
  humanPromptText,
  isHarnessTurn,
} from "../src/harness-turn.ts";

/** What a turn costs at worst: the hook's whole budget is 800 ms. */
const SCAN_BUDGET_MS = 50;

const TASK_NOTIFICATION =
  "<task-notification><task-id>bp1v5vsl4</task-id>" +
  '<summary>Monitor event: "PR #74 CI checks for 493ffb4f"</summary>' +
  "<event>Comment claims (macos-latest): pass</event></task-notification>";

const HUMAN = "why does the OPTA extraction drop events";

describe("every registered shape is recognised from its own sample", () => {
  test.each(HARNESS_SHAPES.map((shape) => [shape.name, shape] as const))("%s", (_, shape) => {
    expect(isHarnessTurn(shape.sample)).toBe(true);
    // An element or a marker is stripped and the human text after it kept;
    // a head makes everything from it on the harness's.
    expect(humanPromptText(`${shape.sample}\n${HUMAN}`)).toBe(shape.kind === "head" ? "" : HUMAN);
  });

  test("the registry names the shapes seen live, and nothing generic", () => {
    expect(HARNESS_SHAPES.map((shape) => shape.name).sort()).toEqual([
      "# Autonomous loop check",
      "# Autonomous loop tick",
      "<agent-message>",
      "<bash-input>",
      "<bash-notification>",
      "<bash-stderr>",
      "<bash-stdout>",
      "<command-args>",
      "<command-message>",
      "<command-name>",
      "<cross-session-message>",
      "<ide_opened_file>",
      "<ide_selection>",
      "<local-command-stderr>",
      "<local-command-stdout>",
      "<system-reminder>",
      "<task-notification>",
      "<teammate-message>",
      "Caveat: The messages below were generated by the user while running local commands.",
      "PostToolUse:",
      "PreToolUse:",
      "Stop hook feedback:",
      "This session is being continued from a previous conversation",
      "[Cross-session idle notice]",
      "[Image #N]",
      "[Request interrupted by user for tool use]",
      "[Request interrupted by user]",
      SYSTEM_NOTIFICATION_MARKER,
    ]);
  });
});

/**
 * THE SHAPES THE ROUND-4 HOLD-OUT SHOWED MISSING (round 4, M2): Claude Code's
 * slash-command echo, local-command output, the interruption notice, the
 * "Caveat" that heads local-command output, the compaction's continuation,
 * Stop-hook feedback, a tool hook's error line and a pasted image's marker.
 * "Caveat: …" reached the PDF-labels tree, "Stop hook feedback: Tests were
 * not run" the flaky-test tree.
 */
/**
 * A QUOTE OF THE AGENT'S OWN ANSWER IS NOT THE HUMAN'S TEXT (round 4, L3):
 * "> The root cause is that the JWKS cache keeps the old key set …" followed
 * by "ok" scored the agent's words, and reached the tree they came from.
 * Only the text outside a "> " quote is the human's.
 */
describe("a quoted line is not the human's text (L3)", () => {
  test("a quote and an acknowledgement leave the acknowledgement", () => {
    const turn = "> The root cause is that the JWKS cache keeps the old key set for 24 hours, so refresh tokens signed with the new kid fail.\nok";
    expect(humanPromptText(turn)).toBe("ok");
  });

  test("a question under a quote keeps the question", () => {
    expect(humanPromptText("> Keep the previous signing key for a day.\n>> earlier: rotate weekly\nwhy does the refresh still fail on staging")).toBe(
      "why does the refresh still fail on staging",
    );
  });

  test("an indented quote is a quote too", () => {
    expect(humanPromptText("the export is slow\n   > quoted answer")).toBe("the export is slow");
  });

  test("a > inside a line is the human's", () => {
    expect(humanPromptText("why is p95 > 900 ms on search")).toBe("why is p95 > 900 ms on search");
  });

  test("a turn that only quotes says nothing", () => {
    expect(humanPromptText("> The cache keeps the old key set.")).toBe("");
  });
});

describe("the round-4 harness turns are nobody's prompt (M2)", () => {
  test.each([
    ["the slash-command echo", "<command-message>review is running…</command-message>\n<command-name>/review</command-name>"],
    ["the slash-command echo with arguments", "<command-name>/compact</command-name>\n<command-message>compact</command-message>\n<command-args>focus on the checkout webhook work</command-args>"],
    ["an interruption", "[Request interrupted by user]"],
    ["an interruption during a tool", "[Request interrupted by user for tool use]"],
    ["local-command output", "<local-command-stdout>Compacted. ctrl+r to see full summary</local-command-stdout>"],
    ["local-command errors", "<local-command-stderr>Error: /model requires an argument</local-command-stderr>"],
    ["the Caveat head", "Caveat: The messages below were generated by the user while running local commands. DO NOT respond to these messages or otherwise consider them in your response unless the user explicitly asks you to."],
    ["a background shell's notice", "<bash-notification><shell-id>bash_3</shell-id><status>completed</status><output>vite v5.4.2 ready in 812 ms</output></bash-notification>"],
    ["the compaction's continuation", "This session is being continued from a previous conversation that ran out of context. The conversation is summarized below:\nThe user asked me to fix duplicate Stripe charges."],
    ["Stop-hook feedback", "Stop hook feedback:\n- Tests were not run. Run bun test before finishing."],
    ["a tool hook's error line", "PostToolUse:Edit hook error: prettier exited with code 2"],
    ["a gate's refusal", "PreToolUse:Write hook error: [Fact-Forcing Gate] present these facts"],
    ["pasted images only", "[Image #1] [Image #2]"],
  ])("%s", (_, turn) => {
    expect(isHarnessTurn(turn)).toBe(true);
  });

  test("a pasted image's marker is stripped, the human's words beside it kept", () => {
    expect(humanPromptText("[Image #1] the hero carousel on the product page loads late, LCP is 4s")).toBe(
      "the hero carousel on the product page loads late, LCP is 4s",
    );
  });

  test("an image marker mid-sentence leaves the words on either side apart", () => {
    expect(humanPromptText("see[Image #12]the banner")).toBe("see the banner");
  });

  test("a hook's name mid-line is the human's", () => {
    expect(humanPromptText("why does the PostToolUse: hook fail on save")).toBe("why does the PostToolUse: hook fail on save");
  });
});

/**
 * A `!` COMMAND'S ECHO IS THE HARNESS'S (round 5, H1): Claude Code hands the
 * model the command as <bash-input> and its output as <bash-stdout> and
 * <bash-stderr>, as a user turn. "On branch feat/orders-csv-export … nothing
 * to commit" reached the CSV-export tree on the branch name.
 */
describe("a shell command's echo is nobody's prompt (round 5, H1)", () => {
  test.each([
    ["the command", "<bash-input>git status</bash-input>"],
    [
      "its output, with an empty error stream",
      "<bash-stdout>On branch feat/orders-csv-export\nYour branch is up to date with 'origin/feat/orders-csv-export'.\n\nnothing to commit, working tree clean</bash-stdout><bash-stderr></bash-stderr>",
    ],
    ["its error stream alone", "<bash-stderr>error: pathspec 'packages/api/src/auth' did not match any file(s) known to git</bash-stderr>"],
  ])("%s", (_, turn) => {
    // Arrange, Act, Assert — the whole turn is the harness's
    expect(isHarnessTurn(turn)).toBe(true);
  });

  test("the human's question after the output is kept", () => {
    // Arrange
    const turn = "<bash-stdout>3 failed, 41 passed</bash-stdout>\nwhy does the checkout e2e fail on CI";

    // Act
    const human = humanPromptText(turn);

    // Assert
    expect(human).toBe("why does the checkout e2e fail on CI");
  });
});

describe("a turn the harness wrote is nobody's prompt", () => {
  test.each([
    ["a task notification", TASK_NOTIFICATION],
    ["the system-notification marker at the head", `${SYSTEM_NOTIFICATION_MARKER}\n${TASK_NOTIFICATION}`],
    ["the marker followed by plain words", `${SYSTEM_NOTIFICATION_MARKER} Monitor event: PR #74 CI checks pass`],
    ["the marker after leading whitespace", `  \n${SYSTEM_NOTIFICATION_MARKER}\nMonitor event: CI checks pass`],
    ["the marker after a byte-order mark", `﻿${SYSTEM_NOTIFICATION_MARKER}\nMonitor event: CI checks pass`],
    ["the marker in another casing", "[System Notification - Not User Input]\nMonitor event: CI checks pass"],
    ["a system reminder before the marker", `<system-reminder>x</system-reminder>\n${SYSTEM_NOTIFICATION_MARKER}\nMonitor event: CI checks pass`],
    ["a system reminder and a blank before the marker, one line", `<system-reminder>x</system-reminder> ${SYSTEM_NOTIFICATION_MARKER} Monitor event: CI checks pass`],
    ["an upper-case element", "<TASK-NOTIFICATION><summary>Monitor event: CI checks pass</summary></TASK-NOTIFICATION>"],
    ["another agent's message", '<agent-message from="a781e1e961b68f4c2">Report: all suites pass</agent-message>'],
    ["another session's message", '<cross-session-message from="ken-laptop">CI checks pass on main</cross-session-message>'],
    ["a teammate's message", '<teammate-message teammate_id="researcher" color="blue">Found the OAuth refresh race</teammate-message>'],
    ["an idle notice", '[Cross-session idle notice] "agentic-main-f0" is idle now — its harness reports: «OpenAPI-Spec fertig»'],
    ["a /loop tick", "# Autonomous loop tick (dynamic pacing)\nCheck the deploy and the CI checks."],
    ["a /loop check", "# Autonomous loop check\nCheck the deploy and the CI checks."],
    ["two wrappers and whitespace", `  ${TASK_NOTIFICATION}\n\n${TASK_NOTIFICATION}  `],
    ["a wrapper cut off before it closes", "<task-notification><summary>Monitor event: PR #74 CI checks"],
  ])("%s has no human text", (_, turn) => {
    expect(humanPromptText(turn)).toBe("");
    expect(isHarnessTurn(turn)).toBe(true);
  });
});

describe("a turn that STARTS with a wrapper is wrapped to that element's LAST close (M1)", () => {
  test.each([
    [
      "a hand-back quoting the closing tag",
      '<agent-message from="a7">\n[Subagent hand-back] the matcher strips <agent-message from=…> up to </agent-message>, so OAuth refresh race findings stay unscored.\n</agent-message>',
    ],
    ["the same element nested", '<agent-message from="a1">outer <agent-message from="b2">inner</agent-message> then the deploy cache bug</agent-message>'],
    [
      "a body that closes early",
      '<cross-session-message from="uds:/tmp/1.sock">done</cross-session-message> look at the gateway upload limit tree</cross-session-message>',
    ],
  ])("%s leaks nothing", (_, turn) => {
    expect(humanPromptText(turn)).toBe("");
  });
});

describe("two wrappers, and a wrapper after the human text (hold-out review, L1)", () => {
  test("two same-tag wrappers keep the human text between them", () => {
    // Arrange — the leading one is wrapped to its last close BEFORE the second opens
    const turn = '<agent-message from="a">report A</agent-message>\nplease compare with the JWT refresh race\n<agent-message from="b">report B</agent-message>';

    // Act + Assert
    expect(humanPromptText(turn)).toBe("please compare with the JWT refresh race");
  });

  test("a leading wrapper that quotes its own close still swallows the quote", () => {
    const turn = '<agent-message from="a">it strips up to </agent-message>, then CI checks pass</agent-message>\nplease compare with the JWT refresh race\n<agent-message from="b">report B</agent-message>';
    expect(humanPromptText(turn)).toBe("please compare with the JWT refresh race");
  });

  test("a wrapper after the human text ends at its FIRST close — what follows is the human's again", () => {
    // Pinned on purpose: a non-leading wrapper cannot tell its own quoted close
    // from a human sentence that names the tag, so the human's words win
    const turn = "fix the checkout test <task-notification>CI checks pass</task-notification> then why does the matcher keep </task-notification>";
    expect(humanPromptText(turn)).toBe("fix the checkout test then why does the matcher keep </task-notification>");
  });

  test.each([
    ["a no-break space", " "],
    ["an ideographic space", "　"],
    ["an em space", " "],
  ])("a head marker after %s at a line start still ends the human text", (_, space) => {
    const turn = `fix it\n${space}${SYSTEM_NOTIFICATION_MARKER}\nMonitor event: CI checks pass on deploy`;
    expect(humanPromptText(turn)).toBe("fix it");
  });
});

describe("the human text around a wrapper is kept, and only it", () => {
  test("text before and after a notification survives; the notification does not", () => {
    const turn = `${HUMAN} ${TASK_NOTIFICATION} after the retry`;
    expect(humanPromptText(turn)).toBe(`${HUMAN} after the retry`);
    expect(isHarnessTurn(turn)).toBe(false);
  });

  test("words on either side of a wrapper never fuse into one", () => {
    expect(humanPromptText(`cache${TASK_NOTIFICATION}key`)).toBe("cache key");
  });

  test.each([
    [
      "the IDE's opened file",
      "<ide_opened_file>The user opened the file /repo/src/auth/refresh.ts in the IDE. This may or may not be related to the current task.</ide_opened_file>\nmache weiter",
      "mache weiter",
    ],
    ["the IDE's selection", "<ide_selection>The user selected the lines 3 to 9:\nconst token = await rotateKey(kid);\n</ide_selection>\nok", "ok"],
    [
      "a queued notification after the human text",
      `fix the flaky checkout test\n\n${SYSTEM_NOTIFICATION_MARKER}\nThis is an automated background-task event.\n${TASK_NOTIFICATION}`,
      "fix the flaky checkout test",
    ],
    [
      "an indented notification queued after the human text",
      `fix the flaky checkout test\n  ﻿${SYSTEM_NOTIFICATION_MARKER}\nMonitor event: CI checks pass`,
      "fix the flaky checkout test",
    ],
  ])("%s", (_, turn, human) => {
    expect(humanPromptText(turn)).toBe(human);
  });
});

describe("everything else is the human's, exactly as typed", () => {
  test.each([
    ["a plain prompt", "why does src/auth/refresh.ts 500 after the key rotation"],
    ["other angle-bracket text", "the <div> in <Player/> overflows; compare <task-id> handling"],
    ["the marker quoted mid-line", `what does ${SYSTEM_NOTIFICATION_MARKER} mean in the hook input`],
    ["a tag that only starts like a wrapper", "<task-notifications> is the wrong element name"],
    ["a heading that only starts like a loop tick", "# Autonomous loops in the scheduler stall after a deploy"],
  ])("%s is untouched", (_, prompt) => {
    expect(humanPromptText(prompt)).toBe(prompt);
    expect(isHarnessTurn(prompt)).toBe(false);
  });

  test("an empty or blank prompt is not a harness turn — there was nothing to wrap", () => {
    expect(isHarnessTurn("")).toBe(false);
    expect(isHarnessTurn("   ")).toBe(false);
  });

  test("ACCEPTED (L4): a human prompt naming an unclosed wrapper loses the text after it", () => {
    // Suppression only: the cost is one hint on that prompt, never a hint
    // the reader did not earn. DESIGN.md §4 records the trade-off.
    expect(humanPromptText("der Matcher erkennt `<task-notification>` nicht, bitte harness-turn.ts fixen")).toBe(
      "der Matcher erkennt `",
    );
  });
});

describe("the scan is linear and bounded (M2)", () => {
  const MEGABYTE = 1_000_000;
  const repeatTo = (unit: string): string => unit.repeat(Math.ceil(MEGABYTE / unit.length)).slice(0, MEGABYTE);

  test.each([
    ["unterminated openings with an attribute", "<agent-message x"],
    ["unterminated openings with a space", "<task-notification "],
    ["nested openings, never closed", "<task-notification>"],
    ["opening and closing pairs", "<agent-message from=a>x</agent-message>"],
    ["a storm of angle brackets", "<"],
    ["plain words", "fix the oauth refresh race "],
  ])("a megabyte of %s finishes inside the budget", (_, unit) => {
    const turn = repeatTo(unit);
    const started = performance.now();
    humanPromptText(turn);
    isHarnessTurn(turn);
    expect(performance.now() - started).toBeLessThan(SCAN_BUDGET_MS);
  });

  test("round 4, M3: a leading wrapper longer than the window is closed in the whole prompt, and the human's task after it kept", () => {
    // Arrange — the hold-out's A17: a 37 KB IDE selection, then the question
    const selection = `<ide_selection>The user selected the lines 1 to 900 from /repo/services/payments/src/webhooks/stripe.ts:\n${"  const order = await createOrder(event.data.object); // TODO\n".repeat(600)}</ide_selection>`;
    const question = "why does this stripe webhook handler create duplicate charges when the event is retried?";
    expect(selection.length).toBeGreaterThan(HARNESS_SCAN_MAX_CHARS);

    // Act + Assert
    expect(humanPromptText(`${selection}\n${question}`)).toBe(question);
  });

  test("M3: a wrapper after the human text that runs past the window ends at its first close, and both sides are kept", () => {
    const wrapper = `<agent-message from="a1">${"report line ".repeat(4_000)}</agent-message>`;
    expect(humanPromptText(`fix the export ${wrapper} and the import`)).toBe("fix the export and the import");
  });

  test("M3: a wrapper that never closes, in the window or after it, still wraps the rest", () => {
    const turn = `<ide_selection>${"x ".repeat(HARNESS_SCAN_MAX_CHARS)} why does the export fail`;
    expect(humanPromptText(turn)).toBe("");
  });

  test("M3: the look past the window is taken once a prompt, so the scan stays linear", () => {
    // Arrange — two selections each longer than the window, human words after each
    const long = (body: string): string => `<ide_selection>${body.repeat(HARNESS_SCAN_MAX_CHARS / body.length + 10)}</ide_selection>`;
    const turn = `${long("a ")} first question ${long("b ")} second question`;

    // Act + Assert — the second wrapper wraps the rest
    expect(humanPromptText(turn)).toBe("first question");
  });

  test("M3: a close past the first mebibyte is not looked for — the wrapper wraps the rest", () => {
    const turn = `<ide_selection>${"z".repeat(1_100_000)}</ide_selection>\n${HUMAN}`;
    expect(humanPromptText(turn)).toBe("");
  });

  test("M3: a megabyte of leading wrapper closed at its very end finishes inside the budget", () => {
    const turn = `<ide_selection>${"y".repeat(MEGABYTE)}</ide_selection>\n${HUMAN}`;
    const started = performance.now();
    const human = humanPromptText(turn);
    expect(performance.now() - started).toBeLessThan(SCAN_BUDGET_MS);
    expect(human).toBe(HUMAN);
  });

  test("only a bounded window after the leading whitespace is read", () => {
    const turn = `${" ".repeat(MEGABYTE)}${HUMAN}${"x".repeat(HARNESS_SCAN_MAX_CHARS)} tail`;
    const human = humanPromptText(turn);
    expect(human.startsWith(HUMAN)).toBe(true);
    expect(human.length).toBeLessThanOrEqual(HARNESS_SCAN_MAX_CHARS);
    expect(human).not.toContain("tail");
  });
});
