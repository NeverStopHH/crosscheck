/**
 * The PATH signal of the generated-target rule — mechanically generated,
 * non-authoritative files by name — and the wire fields that carry a
 * connector's classification. The path signal is the one both sides apply —
 * the connector to every captured path, the hub to every target an older
 * connector sends without the field — so it is pinned here, once.
 */
import { describe, expect, test } from "bun:test";

import {
  GENERATED_LOCKFILE_NAMES,
  TargetSchema,
  isContractLike,
  isGeneratedPath,
  matchesGeneratedName,
  protobufSourceOf,
} from "../src/index.ts";

const TARGET = { workContextId: "wc_1", kind: "file", value: "apps/x/package-lock.json" } as const;

describe("isGeneratedPath — well-known names at ANY depth", () => {
  test("every lockfile name is generated at the root and nested", () => {
    for (const name of GENERATED_LOCKFILE_NAMES) {
      expect(isGeneratedPath(name), name).toBe(true);
      expect(isGeneratedPath(`apps/practice/${name}`), `nested ${name}`).toBe(true);
    }
  });

  test("the lockfiles the release gate names are all in the list", () => {
    // Arrange: the gate's spec list, verbatim.
    const named = [
      "package-lock.json", "pnpm-lock.yaml", "yarn.lock", "bun.lock", "bun.lockb", "Cargo.lock",
      "poetry.lock", "uv.lock", "Gemfile.lock", "composer.lock", "go.sum",
    ];

    // Assert
    expect([...GENERATED_LOCKFILE_NAMES].map(String).sort()).toEqual([...named].sort());
  });

  test("a directory named for machine output, at any depth", () => {
    expect(isGeneratedPath("packages/api/src/__generated__/schema.ts")).toBe(true);
    expect(isGeneratedPath("__generated__/schema.ts")).toBe(true);
    expect(isGeneratedPath("packages/ui/dist/index.js")).toBe(true);
  });

  test("the unambiguous codegen name: *.generated.*", () => {
    expect(isGeneratedPath("packages/api/src/client.generated.ts")).toBe(true);
  });

  test("TIGHTENED: a generated/ directory and a *.gen.* name are no longer suppressed by name", () => {
    // Repos hand-maintain both; the attribute and header signals still catch
    // the ones a generator really writes.
    expect(isGeneratedPath("packages/api/generated/client.ts")).toBe(false);
    expect(isGeneratedPath("src/routes.gen.ts")).toBe(false);
  });

  test("TIGHTENED: a protobuf binding is never generated by name alone — the hub cannot see the .proto", () => {
    for (const path of ["proto/messages_pb2.py", "proto/messages.pb.go", "web/src/messages_pb.ts", "web/src/messages_pb.js"]) {
      expect(isGeneratedPath(path), path).toBe(false);
    }
  });

  test("ordinary files stay ordinary, near-misses included", () => {
    for (const path of [
      "apps/streaming/feed.ts",
      "src/generated.ts",
      "src/generator/index.ts",
      "src/distance.ts",
      "src/a.genuine.ts",
      "docs/lockfile.md",
      "src/package-lock.json.ts",
      "src/messages_pb.tsx",
    ]) {
      expect(isGeneratedPath(path), path).toBe(false);
    }
  });
});

describe("protobufSourceOf — the .proto a binding must sit beside", () => {
  test("each binding suffix names its source", () => {
    expect(protobufSourceOf("proto/messages_pb2.py")).toBe("messages.proto");
    expect(protobufSourceOf("gen/go/messages.pb.go")).toBe("messages.proto");
    expect(protobufSourceOf("web/src/messages_pb.ts")).toBe("messages.proto");
    expect(protobufSourceOf("web/src/messages_pb.js")).toBe("messages.proto");
  });

  test("anything else names none", () => {
    for (const path of ["src/messages.ts", "_pb.ts", "src/messages_pb.tsx", "proto/messages.proto"]) {
      expect(protobufSourceOf(path), path).toBeNull();
    }
  });
});

describe("isContractLike — schemas and migrations are never suppressed by default", () => {
  test("migrations, schema sources and API descriptions look authoritative", () => {
    for (const path of [
      "db/migrations/0042_add_index.py",
      "prisma/migrations/20261008_init/migration.sql",
      "db/migrate/20261008_add_users.rb",
      "proto/messages.proto",
      "api/schema.graphql",
      "api/openapi.json",
      "api/v2.swagger.yaml",
      "schemas/user.schema.json",
      "prisma/schema.prisma",
    ]) {
      expect(isContractLike(path), path).toBe(true);
    }
  });

  test("a generated NAME that is also a contract stays evidence", () => {
    // The raw name rule fires; the guard keeps it out of the path signal.
    expect(matchesGeneratedName("api/schema.generated.graphql")).toBe(true);
    expect(isGeneratedPath("api/schema.generated.graphql")).toBe(false);
    expect(isGeneratedPath("dist/openapi.json")).toBe(false);
  });

  test("typings generated FROM a schema are not a contract: __generated__/schema.ts stays suppressed", () => {
    expect(isContractLike("packages/api/src/__generated__/schema.ts")).toBe(false);
    expect(isGeneratedPath("packages/api/src/__generated__/schema.ts")).toBe(true);
  });
});

describe("TargetSchema.authoritative — the connector's word that a generated file counts", () => {
  test("true round-trips; garbage reads as absent and keeps the touch", () => {
    expect(TargetSchema.parse({ ...TARGET, authoritative: true }).authoritative).toBe(true);
    const garbled = TargetSchema.safeParse({ ...TARGET, authoritative: "yes please" });
    expect(garbled.success).toBe(true);
    expect(garbled.data?.authoritative).toBeUndefined();
  });
});

describe("TargetSchema.generated — additive, optional, tolerant", () => {
  test("a target without the field parses, unlabelled", () => {
    const result = TargetSchema.parse(TARGET);

    expect(result.generated).toBeUndefined();
  });

  test("each signal round-trips", () => {
    for (const signal of ["path", "attribute", "header"] as const) {
      expect(TargetSchema.parse({ ...TARGET, generated: signal }).generated).toBe(signal);
    }
  });

  test("a value this build does not know reads as ORDINARY, and the touch is kept", () => {
    // Act: a newer connector's label, or garbage.
    const result = TargetSchema.safeParse({ ...TARGET, generated: "vendored-by-a-future-build" });

    // Assert: the record is accepted and the label is gone — never a reason to drop the touch.
    expect(result.success).toBe(true);
    expect(result.data?.generated).toBeUndefined();
  });
});
